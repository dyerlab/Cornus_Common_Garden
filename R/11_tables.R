# ---- Tab_CovariateEffects --------------------------------
# Publication layout: one row per response x subset, one column per covariate,
# showing the coefficient with its standard error and a significance mark.
# Panel A: survival (logit scale). Panel B: growth traits (ln scale).

coef_cell <- function(est, se, p) {
  ifelse(is.na(est), "—",
    sprintf("%+.3f (%.3f)%s", est, se, star(p)))
}

sfe <- rd("survival_fixed_effects.csv") %>%
  filter(model %in% c("full_family", "native_family", "cultivar_family"),
         term %in% c("days_z", "seed_weight_z")) %>%
  mutate(subset = recode(model, full_family = "Total", native_family = "Native",
                         cultivar_family = "Cultivar"),
         term = recode(term, days_z = "Germination timing", seed_weight_z = "Seed weight")) %>%
  transmute(Response = "Survival", Subset = subset, term, cell = coef_cell(estimate, se, p)) %>%
  pivot_wider(names_from = term, values_from = cell)

gcov <- rd("growth_covariates.csv") %>%
  mutate(Response = trait_lab[trait],
         term = recode(term, days_z = "Germination timing", seed_weight_z = "Seed weight")) %>%
  filter(term %in% c("Germination timing", "Seed weight")) %>%
  transmute(Response, Subset = subset, term, cell = coef_cell(estimate, se, p)) %>%
  pivot_wider(names_from = term, values_from = cell)

cov_tab <- bind_rows(sfe, gcov) %>%
  mutate(Response = factor(Response, levels = c("Survival", unname(trait_lab))),
         Subset = factor(Subset, levels = c("Total", "Native", "Cultivar"))) %>%
  arrange(Response, Subset) %>%
  select(Response, Subset, `Germination timing`, `Seed weight`)

w("\n## Tab_CovariateEffects\n")
w("Estimated effects of the two family-level covariates on survival (logit scale) ",
  "and each growth trait (ln scale), from the family model, for the full sample and ",
  "within each origin class. Cells give the coefficient (SE). Germination timing is ",
  "scaled developmental time since germination (higher = earlier germination, more ",
  "growing time); seed weight is the scaled maternal family mean. ",
  "· p<0.1, * p<0.05, ** p<0.01, *** p<0.001.\n")
writeLines(md_table(cov_tab), out)

