fmt_qg <- function(df) {
  df %>% transmute(
    Trait = trait_lab[trait], Model = model, Sensitivity = sensitivity,
    Removed = ifelse(is.na(removed), "—", removed),
    `V origin` = ifelse(is.na(estimate_V_origin), "—",
      paste0(ci(estimate_V_origin, ci_low_V_origin, ci_high_V_origin), star(p_origin))),
    `V family` = paste0(ci(estimate_V_family, ci_low_V_family, ci_high_V_family), star(p_family)),
    `V residual` = ci(estimate_V_residual, ci_low_V_residual, ci_high_V_residual),
    h2 = ci(estimate_h2, ci_low_h2, ci_high_h2))
}
gq <- rd("growth_quantgen.csv"); goq <- rd("growth_origin_quantgen.csv")
w("\n## Tab_GrowthHeritability\n")
w("Variance components and half-sib heritability for the single-time traits, with a ",
