md_table <- function(df, digits = 3) {
  fmt_num <- function(x) {
    if (all(is.na(x) | x == round(x))) return(ifelse(is.na(x), "—", as.character(as.integer(x))))
    ifelse(is.na(x), "—", formatC(x, format = "f", digits = digits))
  }
  df <- df %>% mutate(across(where(is.numeric), fmt_num))
  hdr  <- paste0("| ", paste(names(df), collapse = " | "), " |")
  sep  <- paste0("| ", paste(rep("---", ncol(df)), collapse = " | "), " |")
  body <- apply(df, 1, function(r) paste0("| ", paste(r, collapse = " | "), " |"))
  c(hdr, sep, body)
}
ci <- function(est, lo, hi, d = 3) ifelse(is.na(est), "—",
  sprintf(paste0("%.", d, "f [%.", d, "f, %.", d, "f]"), est, lo, hi))
star <- function(p) ifelse(is.na(p), "", ifelse(p < .001, "***", ifelse(p < .01, "**", ifelse(p < .05, "*", ifelse(p < .1, "·", "")))))

