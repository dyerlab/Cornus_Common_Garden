# ---- Tab_Survival ----------------------------------------------

sa <- rd("survival_aic.csv"); sq <- rd("survival_quantgen.csv")
sq_w <- sq %>% select(set, parameter, estimate, ci_low, ci_high) %>%
  pivot_wider(names_from = parameter, values_from = c(estimate, ci_low, ci_high))
surv_tab <- sa %>%
  mutate(join_set = case_when(
    subset == "Total"    & model == "family"          ~ "Total_family",
    subset == "Total"    & model == "origin + family" ~ "Total_origin_family",
    subset == "Native"   & model == "family"          ~ "Native_family",
    subset == "Cultivar" & model == "family"          ~ "Cultivar_family",
    subset == "AP"       & model == "family"          ~ "AP_family",
    TRUE ~ NA_character_)) %>%
  left_join(sq_w, by = c("join_set" = "set")) %>%
  transmute(Subset = subset, Model = model,
            AICc = round(AICc, 2), dAICc = round(dAICc, 2), wAICc = round(wAICc, 3),
            `V origin` = ci(estimate_V_origin, ci_low_V_origin, ci_high_V_origin),
            `V family` = ci(estimate_V_family, ci_low_V_family, ci_high_V_family),
            `P family` = ifelse(is.na(estimate_P_family), "—", sprintf("%.3f", estimate_P_family)),
            h2 = ci(estimate_h2, ci_low_h2, ci_high_h2))
